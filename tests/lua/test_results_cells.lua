vim.opt.runtimepath:append(vim.fn.getcwd())
local results = require("better_sql.results")
local function key(keys)
  vim.api.nvim_feedkeys(vim.api.nvim_replace_termcodes(keys, true, false, true), "xt", false)
end
local raw = 'first\nsecond\t"quoted"'
local buf = results.show({ sets = {
  { columns = { { name = "界" }, { name = "value" }, { name = "empty" } }, rows = {
    { { text = "界", is_null = false }, { text = raw, is_null = false }, { text = "", is_null = false } },
    { { text = "二", is_null = false }, { text = "", is_null = true }, { text = "", is_null = false } },
  }, status = "SELECT 2", truncated = true },
  { columns = {}, rows = {}, status = "UPDATE 1" },
  { columns = { { name = "zero" } }, rows = {}, status = "SELECT 0" },
} })
key("l")
key('"ayc')
assert(vim.fn.getreg("a") == raw, "copy must use the raw cell, including newlines and tabs")
key("K")
local detail = vim.api.nvim_get_current_buf()
local content = table.concat(vim.api.nvim_buf_get_lines(detail, 0, -1, false), "\n")
assert(content:find(raw, 1, true), "detail must show multiline cell content")
assert(not vim.bo[detail].modifiable)
key("q")
assert(vim.api.nvim_get_current_buf() == buf, "closing detail must return to results")
key("j")
key("yc")
assert(vim.fn.getreg('"') == "NULL", "NULL cells must copy as NULL")
key("l")
key("yc")
assert(vim.fn.getreg('"') == "", "empty strings must copy as empty strings")
key("h")
key("k")
key("yc")
assert(vim.fn.getreg('"') == raw, "row navigation must retain the selected column")
key("99j")
key("yc")
assert(vim.fn.getreg('"') == "NULL", "row counts must clamp at the last row")
key("99h")
key("yc")
assert(vim.fn.getreg('"') == "二", "column counts must clamp at the first column")
key("2k")
key("yc")
assert(vim.fn.getreg('"') == "界", "counted row movement must preserve Unicode cells")
results.select_set(2)
vim.fn.setreg('"', "unchanged")
key("yc")
key("K")
assert(vim.fn.getreg('"') == "unchanged", "command results have no copyable cells")
results.select_set(3)
key("j")
key("l")
assert(vim.api.nvim_get_current_buf() == buf, "empty results must remain navigable")
results.select_set(1)
vim.api.nvim_win_set_cursor(0, { 1, 0 })
key("yc")
assert(vim.fn.getreg('"') == "unchanged", "metadata must not copy a stale selection")
key("j")
key("l")
key("yc")
assert(vim.fn.getreg('"') == raw)
key("K")
detail = vim.api.nvim_get_current_buf()
vim.api.nvim_buf_delete(buf, { force = true })
assert(not vim.api.nvim_buf_is_valid(detail), "old detail buffers must be wiped")
assert(results.export_data() == nil, "wiping results must clear their export data")
print("result cell controls passed")
